-- DISASTER-X AI — PostgreSQL 15 + PostGIS 3.4 schema (Phase 2)
-- Apply:  psql -f db/schema.sql
-- Reflects the entities the inference API and alert engine produce.

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ---------------------------------------------------------------- regions
CREATE TABLE regions (
    id           SERIAL PRIMARY KEY,
    code         TEXT UNIQUE NOT NULL,          -- e.g. 'N33W090' (AI4G tile id)
    name         TEXT NOT NULL,                 -- e.g. 'Mississippi (USA)'
    country      TEXT,
    geometry     geometry(Polygon, 4326) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------ model versions
CREATE TABLE model_versions (
    id            SERIAL PRIMARY KEY,
    name          TEXT NOT NULL,                -- 'susceptibility_rf_v2'
    artifact_path TEXT NOT NULL,                -- 'ml/models/...joblib'
    task          TEXT NOT NULL,
    metrics       JSONB NOT NULL,               -- {"test_auc": 0.832, ...}
    trained_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (name, artifact_path)
);

-- ------------------------------------------------------------ observations
-- Raw evidence rows feeding the susceptibility model (2014-2019 window).
CREATE TABLE observations (
    id             BIGSERIAL PRIMARY KEY,
    region_id      INT NOT NULL REFERENCES regions(id),
    observed_at    DATE NOT NULL,
    source         TEXT NOT NULL,               -- 'sentinel-1-sar'
    measurement    JSONB NOT NULL,              -- flexible payload
    geom           geometry(Point, 4326) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX obs_region_time_idx ON observations (region_id, observed_at DESC);
CREATE INDEX obs_geom_idx ON observations USING GIST (geom);

-- ------------------------------------------------------------- predictions
-- One row per grid cell per model run (0.05 deg cells).
CREATE TABLE predictions (
    id             BIGSERIAL PRIMARY KEY,
    model_version_id INT NOT NULL REFERENCES model_versions(id),
    region_id      INT NOT NULL REFERENCES regions(id),
    cell_geom      geometry(Polygon, 4326) NOT NULL,
    cell_center    geometry(Point, 4326) NOT NULL,
    risk_p         REAL NOT NULL CHECK (risk_p BETWEEN 0 AND 1),
    risk_tier      TEXT NOT NULL CHECK (risk_tier IN ('low','moderate','moderate-high','high')),
    features       JSONB,
    drivers        JSONB,                       -- top-3 explainability drivers
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX pred_model_idx     ON predictions (model_version_id, created_at DESC);
CREATE INDEX pred_geom_idx      ON predictions USING GIST (cell_geom);
CREATE INDEX pred_tier_idx      ON predictions (risk_tier);
-- index for querying the latest run per cell per model
CREATE INDEX pred_latest_idx ON predictions (model_version_id, cell_center, created_at DESC);

-- ------------------------------------------------------------------ alerts
-- Generated by the rule-based alert engine on top of predictions.
CREATE TABLE alerts (
    id             BIGSERIAL PRIMARY KEY,
    prediction_id  BIGINT NOT NULL REFERENCES predictions(id),
    region_id      INT NOT NULL REFERENCES regions(id),
    severity       TEXT NOT NULL CHECK (severity IN ('watch','warning','critical')),
    rule           TEXT NOT NULL,               -- e.g. 'risk_p >= 0.8278'
    message        TEXT NOT NULL,
    drivers        JSONB,                       -- copied from prediction for the UI
    status         TEXT NOT NULL DEFAULT 'active'
                   CHECK (status IN ('active','acknowledged','resolved','dismissed')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at    TIMESTAMPTZ
);
CREATE INDEX alerts_status_idx ON alerts (status, created_at DESC);
CREATE INDEX alerts_region_idx ON alerts (region_id, created_at DESC);

-- ------------------------------------------------------------- users/roles
CREATE TABLE app_users (
    id           SERIAL PRIMARY KEY,
    email        TEXT UNIQUE NOT NULL,
    full_name    TEXT,
    role         TEXT NOT NULL DEFAULT 'analyst'
                 CHECK (role IN ('analyst','emergency_manager','admin')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE alert_acknowledgements (
    alert_id  BIGINT NOT NULL REFERENCES alerts(id),
    user_id   INT     NOT NULL REFERENCES app_users(id),
    note      TEXT,
    ack_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (alert_id, user_id)
);

